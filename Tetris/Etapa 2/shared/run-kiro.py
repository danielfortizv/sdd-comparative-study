"""Researcher launcher: exact seed, native Kiro V3 spec mode, durable raw evidence."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import subprocess
import time
from datetime import datetime, timezone

STAGE = Path(__file__).resolve().parent.parent
ROOT = STAGE / "Kiro"
DOCS = ROOT / "docs"
SEED_SHA = "63919779DD4104076FBABCB130CE296A160FA840E0B4755A2AA5D90757ADA8EF"

def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest().upper()

def now():
    return datetime.now(timezone.utc).isoformat()

def save(path, data):
    path.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--phase", choices=["specify", "implement", "clarify"], required=True)
    parser.add_argument("--label", required=True)
    parser.add_argument("--clarification-file", type=Path)
    parser.add_argument("--resume-id")
    parser.add_argument("--prepare-only", action="store_true", help="Save an immutable prompt/control record without starting Kiro")
    parser.add_argument("--use-prepared", action="store_true", help="Submit an already prepared, hash-matching prompt without rewriting it")
    args = parser.parse_args()
    if not args.label or any(c not in "abcdefghijklmnopqrstuvwxyz0123456789-" for c in args.label):
        raise ValueError("Unsafe evidence label")
    if not (ROOT / ".kiro" / "specs" / "tetris-stage1-option-a").is_dir():
        raise RuntimeError("Own inherited Kiro specifications are missing")
    DOCS.mkdir(exist_ok=True)
    paths = {key: DOCS / f"{args.label}.{suffix}" for key, suffix in {
        "prompt": "prompt.txt", "stdout": "stdout.jsonl", "stderr": "stderr.txt",
        "started": "started.json", "run": "run.json"}.items()}
    if any(path.exists() for key, path in paths.items() if key != "prompt"):
        raise FileExistsError("Invocation labels are immutable; choose a new one")
    if paths["prompt"].exists() and not args.use_prepared:
        raise FileExistsError("Prompt exists; reuse only with --use-prepared and an exact matching preparation record")
    seed_path = STAGE / "shared" / "seed.md"
    if sha(seed_path) != SEED_SHA:
        raise RuntimeError("Frozen common seed changed")
    seed = "\n".join(line[2:] if line.startswith("> ") else line[1:]
                     for line in seed_path.read_text(encoding="utf-8-sig").splitlines()
                     if line.startswith(">" )).strip()
    control = (
        "Use Kiro's actual native V3 spec mode and Auto model. Use English. Work only in this tool's Stage 2 directory. "
        "Start from this tool's own Stage 1 source/specifications; do not read or copy another tool's implementation/specs. "
        "Preserve the inherited .kiro/specs/tetris-stage1-option-a/ files. New feature artifacts belong under "
        ".kiro/specs/tetris-stage2-option-a/. No Git branch, commit, push, repository upload, automatic tool update, "
        "credential output, changes to Stage 1/shared toolchain, or delegation. The researcher only prepares environment, "
        "measurement and evidence; all application/test/specification changes must be generated by you after native specification revision."
    )
    if args.phase == "specify":
        task = (
            "Inspect this own inherited implementation and specifications. Use the native Feature Spec lifecycle to write "
            "requirements.md (atomic requirements and explicit acceptance scenarios), design.md and tasks.md in the new feature directory. "
            "The user authorizes completing all three specification phases autonomously. Do not change application code, tests, "
            "dependencies, inherited specs or researcher evidence files in this invocation. Record material ambiguities and meaningful "
            "verification plans, keeping implementation tasks unchecked. Complete those three artifacts on disk, then stop before implementation."
        )
    elif args.phase == "implement":
        task = (
            "Implement the complete approved native feature specification and its tasks. The user authorizes local implementation, "
            "compatible dependency installation and validation. Preserve all inherited regression assertions. Add meaningful tests of production paths. "
            "Run backend tests with docs/coverage.xml and frontend tests with full production-src LCOV at frontend/coverage/lcov.info, "
            "production TypeScript build and dependency audit, saving exact outputs and exit statuses under docs. If a defect is found, "
            "revise the native feature specification first, then adjust code/tests through Kiro. Do not stop at a plan or next-step announcement. "
            "Complete the implementation and actual checks, marking only verified tasks and reporting limitations."
        )
    else:
        if args.clarification_file is None:
            raise ValueError("Clarification file required")
        task = "Apply the recorded correction below through native specification revision before any code/test change."
    if args.clarification_file:
        task += "\n\nRecorded workflow/verification clarification:\n" + args.clarification_file.read_text(encoding="utf-8-sig")
    prompt = control + "\n\n" + task + "\n\nCommon seed (unchanged):\n" + seed
    if args.use_prepared:
        prepared_record = json.loads((DOCS / f"{args.label}.prepared.json").read_text(encoding="utf-8"))
        if (paths["prompt"].read_text(encoding="utf-8") != prompt
                or sha(paths["prompt"]) != prepared_record["prompt_sha256"]):
            raise RuntimeError("Prepared prompt content/hash differs from the requested invocation")
    else:
        paths["prompt"].write_text(prompt, encoding="utf-8")
    # Codex sandbox redirects LOCALAPPDATA; execute the observed real installation.
    exe = Path(os.environ["USERPROFILE"]) / "AppData" / "Local" / "Kiro-Cli" / "kiro-cli.exe"
    pin_file = DOCS / "kiro-runtime-pin.json"
    pin = {"path": str(exe), "sha256": sha(exe), "version": subprocess.check_output(
        [str(exe), "--version"], text=True).strip()}
    if pin_file.exists():
        old = json.loads(pin_file.read_text(encoding="utf-8-sig"))
        if old != pin:
            raise RuntimeError("Kiro runtime changed since initial pin")
    else:
        save(pin_file, pin)
    command = [str(exe), "chat", "--v3", "--mode", "spec", "--model", "auto",
               "--no-interactive", "--trust-all-tools", "--output-format", "stream-json"]
    if args.resume_id:
        command += ["--resume-id", args.resume_id]
    # Direct argument list avoids shell interpolation and preserves multiline text.
    command.append(prompt)
    env = os.environ.copy()
    env["LOCALAPPDATA"] = str(exe.parent.parent)
    env["APPDATA"] = str(Path(os.environ["USERPROFILE"]) / "AppData" / "Roaming")
    env["PATH"] = str(ROOT / "backend" / ".venv" / "Scripts") + os.pathsep + env["PATH"]
    env["PYTHONUTF8"] = "1"
    env["PYTHONDONTWRITEBYTECODE"] = "1"
    record = {"researcher_created": True, "label": args.label, "phase": args.phase,
        "workflow": "Kiro native V3 spec mode", "requested_model": "auto",
        "runtime": pin, "started": now(), "prompt_sha256": sha(paths["prompt"]),
        "seed_sha256": SEED_SHA, "seed_block_sha256": hashlib.sha256(seed.encode()).hexdigest().upper(),
        "prompt_characters": len(prompt), "submission_method": "direct subprocess argument list, complete multiline prompt",
        "resume_id": args.resume_id, "stdout": str(paths["stdout"]), "stderr": str(paths["stderr"])}
    if args.prepare_only:
        record.pop("started")
        record.update(prepared_at_utc=now(), status="prepared_not_submitted",
                      model_invocation_started=False,
                      note="Prompt preparation only; no inference, session or usage is attributed to this record.")
        prepared = DOCS / f"{args.label}.prepared.json"
        if prepared.exists():
            raise FileExistsError("Prepared record exists")
        save(prepared, record)
        print(json.dumps(record, ensure_ascii=False))
        return 0
    save(paths["started"], record)
    start = time.perf_counter()
    with paths["stdout"].open("xb") as out, paths["stderr"].open("xb") as err:
        child = subprocess.Popen(command, cwd=ROOT, env=env, stdout=out, stderr=err)
        record["owned_process_id"] = child.pid
        save(paths["started"], record)
        code = child.wait()
    record.update(ended=now(), duration_seconds=round(time.perf_counter()-start, 3), exit_code=code,
                  stdout_sha256=sha(paths["stdout"]), stderr_sha256=sha(paths["stderr"]))
    save(paths["run"], record)
    print(json.dumps(record, ensure_ascii=False))
    return code

if __name__ == "__main__":
    raise SystemExit(main())
