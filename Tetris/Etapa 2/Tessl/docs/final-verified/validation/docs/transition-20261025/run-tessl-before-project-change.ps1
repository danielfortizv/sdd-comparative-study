param(
    [Parameter(Mandatory=$true)][ValidateSet('specify','implement','clarify')][string]$Phase,
    [Parameter(Mandatory=$true)][string]$Label,
    [string]$Clarification,
    [switch]$Resume
)

# Researcher launcher. Tessl supplies MCP/plugin context; it has no spec/build command.
$ErrorActionPreference='Stop'
$toolRoot=(Get-Location).Path
$stageRoot=Split-Path -Parent $toolRoot
$caseRoot=Split-Path -Parent $stageRoot
$docs=Join-Path $toolRoot 'docs'
$geminiEntry=Join-Path $caseRoot 'Etapa 1\_toolchain\node_modules\@google\gemini-cli\bundle\gemini.js'
$seedPath=Join-Path $stageRoot 'shared\seed.md'
if (-not (Test-Path -LiteralPath (Join-Path $toolRoot 'tessl.json'))) {throw 'Tessl Stage2 project is missing.'}
$tesslPin=Get-Content -LiteralPath (Join-Path $docs 'tessl-runtime-pin.json') -Raw | ConvertFrom-Json
$tesslExe=$tesslPin.runtime_path
if (-not $tesslExe) {$tesslExe=$tesslPin.path}
if (-not $tesslExe) {$tesslExe=$tesslPin.executable}
if (-not $tesslExe) {throw 'Missing pinned Tessl runtime path.'}
$tesslHash=$tesslPin.runtime_sha256
if (-not $tesslHash) {$tesslHash=$tesslPin.sha256}
if ((Get-FileHash -LiteralPath $tesslExe -Algorithm SHA256).Hash -ne $tesslHash) {throw 'Pinned Tessl runtime hash changed.'}
$seed=((Get-Content -LiteralPath $seedPath -Encoding utf8 | Where-Object {$_ -match '^>'} | ForEach-Object {$_ -replace '^> ?',''}) -join "`n").Trim()
if (-not $seed.StartsWith('Extend the existing Stage 1')) {throw 'Unexpected common seed.'}
if ((Get-FileHash -LiteralPath $seedPath -Algorithm SHA256).Hash -ne '63919779DD4104076FBABCB130CE296A160FA840E0B4755A2AA5D90757ADA8EF') {throw 'Frozen common seed hash changed.'}
$control=@'
Use the existing Tessl vendored project, actual Tessl MCP tools and installed plugin context, matching this tool's Stage 1 workflow. Tessl is a context/plugin integration here, not a native spec/build generator; do not invent Tessl commands. Use English. Work only in this Stage 2 tool directory. Do not read or copy another tool's implementation/specifications. No delegation, Git branch/commit/push, repository upload, Stage1/shared-toolchain edit, automatic tool update, or credential output. Preserve inherited source/tests and Stage1 specifications; new feature specifications go under specs/stage2/. Application/test changes must be generated by you after specification revision. Researcher helpers live under shared/ or docs/ and are not generated application source.
'@
switch ($Phase) {
    'specify' {$task=@'
First inspect tessl.json, .tessl/RULES.md, project AGENTS.md and existing app/specs. Call the actual Tessl MCP status/available-skills/documentation search tools as appropriate and retain their real results; do not claim integration merely because a file exists. Write atomic Stage2 requirements and explicit acceptance scenarios in specs/stage2/requirements.md and a traceable implementation/verification checklist plus material ambiguities in specs/stage2/session_notes.md. Follow this project's existing specification convention. Preserve specs/requirements.md and specs/session_notes.md as the inherited baseline. Do not change application code, tests, dependencies or inherited specifications yet. Finish the specifications on disk and report concrete files and unresolved ambiguities. The full unchanged common seed follows.
'@}
    'implement' {$task=@'
Implement all Stage2 requirements through the existing Tessl MCP/plugin-assisted workflow using specs/stage2/requirements.md and specs/stage2/session_notes.md. The user has authorized the complete local implementation. Use the actual installed Tessl context/skills, preserving the authoritative FastAPI backend and existing React/TypeScript application. Implement meaningful production-path tests and retain Stage1 regression assertions. Run backend tests with coverage XML at docs/coverage.xml, frontend tests with all-src LCOV, TypeScript production build and dependency audit. Record exact outputs and exit statuses under docs. Mark checklist items only when verified. If a defect is found, revise the native project specifications before adjusting app/test code. Do not stop with a plan or a next-step announcement; complete the authorized implementation and report actual checks plus limitations. The full unchanged common seed follows.
'@}
    'clarify' {if (-not $Clarification) {throw 'Clarification required.'}; $task=$Clarification}
}
if ($Phase -ne 'clarify' -and $Clarification) {$task += "`n`nRecorded workflow clarification:`n$Clarification"}
$request="$control`n`n$task`n`nCommon seed (unchanged):`n$seed"
New-Item -ItemType Directory -Force -Path $docs | Out-Null
$promptPath=Join-Path $docs "$Label.prompt.txt"
$stdout=Join-Path $docs "$Label.stdout.json"
$stderr=Join-Path $docs "$Label.stderr.txt"
$runPath=Join-Path $docs "$Label.run.json"
foreach ($p in @($promptPath,$stdout,$stderr,$runPath,(Join-Path $docs "$Label.started.json"))) {if (Test-Path -LiteralPath $p) {throw "Refusing to overwrite $p"}}
[IO.File]::WriteAllText($promptPath,$request,[Text.UTF8Encoding]::new($false))
$env:GOOGLE_GENAI_USE_VERTEXAI='true'
$env:GOOGLE_CLOUD_PROJECT='project-e6384dd1-d4d3-4a03-948'
$env:GOOGLE_CLOUD_LOCATION='global'
$env:GEMINI_MODEL='gemini-3.5-flash'
$env:GOOGLE_APPLICATION_CREDENTIALS=Join-Path $env:APPDATA 'gcloud\application_default_credentials.json'
$env:GEMINI_CLI_TRUST_WORKSPACE='true'
$env:GEMINI_CLI_HOME=Join-Path $docs 'gemini-home'
$env:TESSL_AUTO_UPDATE_INTERVAL_MINUTES='0'
$env:TESSL_DISABLE_UPDATE='1'
$env:PATH=(Join-Path $toolRoot 'backend\.venv\Scripts')+';'+(Join-Path $caseRoot 'Etapa 1\_toolchain\node_modules\.bin')+';'+(Join-Path $caseRoot 'Etapa 1\_toolchain\venv\Scripts')+';'+$env:PATH
if (-not (Test-Path -LiteralPath $env:GOOGLE_APPLICATION_CREDENTIALS)) {throw 'Application Default Credentials missing.'}
$start=Get-Date
$record=[ordered]@{label=$Label;phase=$Phase;workflow='Gemini CLI with Tessl MCP and vendored plugin context';submission_method='complete multiline plain prompt via direct Node entrypoint';started=$start.ToString('o');prompt_sha256=(Get-FileHash -LiteralPath $promptPath -Algorithm SHA256).Hash;seed_sha256=(Get-FileHash -LiteralPath $seedPath -Algorithm SHA256).Hash;requested_model='gemini-3.5-flash';gemini_cli_version='0.60.0';tessl_runtime=$tesslPin;resume_requested=[bool]$Resume}
$record | ConvertTo-Json -Depth 8 | Set-Content -LiteralPath (Join-Path $docs "$Label.started.json") -Encoding utf8
$argsTask=@($geminiEntry,'-m','gemini-3.5-flash','--approval-mode','yolo','--output-format','json','-p',$request)
if ($Resume) {$argsTask=@($geminiEntry,'--resume','latest')+$argsTask[1..($argsTask.Length-1)]}
& node @argsTask 1> $stdout 2> $stderr
$exitTask=$LASTEXITCODE
$end=Get-Date
$record['ended']=$end.ToString('o')
$record['duration_seconds']=[Math]::Round(($end-$start).TotalSeconds,3)
$record['exit_code']=$exitTask
$record['stdout']=$stdout
$record['stderr']=$stderr
$record | ConvertTo-Json -Depth 8 | Set-Content -LiteralPath $runPath -Encoding utf8
Write-Output ($record | ConvertTo-Json -Compress -Depth 8)
exit $exitTask
