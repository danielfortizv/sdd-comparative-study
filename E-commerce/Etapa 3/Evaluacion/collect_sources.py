"""Collect a hash inventory of empirical sources; do not calculate study metrics."""
from pathlib import Path
from datetime import datetime, timezone
import hashlib
import json

stage = Path(__file__).resolve().parent.parent
evidence = stage / 'Evaluacion'
tools = ['OpenSpec', 'Kiro', 'Tessl', 'Spec Kit']
records = []

def add(path, role, tool=None):
    if not path.is_file():
        return
    content = path.read_bytes()
    records.append({'path': path.relative_to(stage).as_posix(), 'tool': tool,
                    'role': role, 'bytes': len(content),
                    'sha256': hashlib.sha256(content).hexdigest()})

add(evidence/'SEED-3.md', 'common-seed')
for tool in tools:
    folder = evidence/tool
    for p in sorted(folder.iterdir()):
        if not p.is_file():
            continue
        if p.name == 'starting-snapshot.json':
            role = 'inherited-source-hashes'
        elif 'prompt' in p.name:
            role = 'submitted-prompt'
        elif 'metadata' in p.name:
            role = 'run-provenance'
        elif p.suffix == '.zip':
            role = 'kiro-session-archive'
        elif p.suffix == '.jsonl':
            role = 'native-session-events'
        elif 'stderr' in p.name:
            role = 'raw-console-errors'
        elif p.suffix == '.txt' and 'validation' in p.name:
            role = 'independent-local-validation'
        elif p.suffix == '.json':
            role = 'raw-console-statistics-and-response'
        else:
            continue
        add(p, role, tool)
    add(stage/tool/'backend'/'coverage.xml', 'backend-raw-coverage', tool)
    add(stage/tool/'frontend'/'coverage'/'lcov.info', 'frontend-raw-coverage', tool)

manifest = {
    'collected_utc': datetime.now(timezone.utc).isoformat(),
    'stage': 3,
    'scope': 'E-commerce Option A: E2E, CI, multi-stage containers, safe API caching',
    'notes': [
        'No cost, quality, coverage percentage or interaction metrics calculated by this collector.',
        'Kiro CLI ZIP contains the same stream JSONL and raw usage event also retained uncompressed; do not count duplicates.',
        'Kiro partial IDE attempt and CLI attempt are distinct sources. Surface/version change is recorded in run-metadata.json.',
        'Some Gemini attempts were interrupted by provider 429s or orchestration issues before final console statistics; use native event telemetry and retain unavailable values as unavailable.',
        'Gemini console statistics may include auxiliary utility-model roles as well as the fixed main model; preserve their separate accounting.',
        'Follow-up prompt files record operational recovery and corrections; an empty corrections list in initial metadata is not a claim that no later prompts were submitted.',
        'Docker and remote GitHub Actions execution are not claimed. Local executed checks are evidenced by native session outputs.',
        'Start-Kiro.ps1 is an experiment-driver launcher updated to the native CLI; it is not application implementation generated by the evaluated tool.'
    ],
    'sources': records
}
(evidence/'source-manifest.json').write_text(json.dumps(manifest, indent=2), encoding='utf-8')
print(f'Inventoried {len(records)} empirical source files.')
